import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { receiptGamesQr as qr } from "../../../tools/receipt-bridge/receipt-games-qr.mjs";

// Copy only the already-reviewed fixed QR, never receipt or caller input.
// Validate its complete thermal raster so row order, scale and quiet zone cannot
// silently diverge when this pure Java asset is regenerated.
assert.equal(qr.targetUrl, "https://mealdeck.co.uk/play/receipt");
assert.equal(qr.displayUrl, "mealdeck.co.uk/play");
assert.equal(qr.heading, "Got a minute? Play MealDeck");
assert.equal(qr.subtitle, "Scan for free food games");
assert.equal(qr.moduleCount, 33);
assert.equal(qr.quietZone, 4);
assert.equal(qr.scale, 6);
assert.equal(qr.gridSize, qr.moduleCount + qr.quietZone * 2);
assert.equal(qr.width, 246);
assert.equal(qr.height, qr.width);
assert.equal(qr.rowBytes, Math.ceil(qr.width / 8));
assert.equal(qr.moduleRows.length, qr.moduleCount);
assert.ok(qr.moduleRows.every((row) => /^[01]{33}$/.test(row)));

const raster = Buffer.alloc(qr.rowBytes * qr.height);
for (let y = 0; y < qr.height; y++) {
  for (let x = 0; x < qr.width; x++) {
    const row = Math.floor(y / qr.scale) - qr.quietZone;
    const column = Math.floor(x / qr.scale) - qr.quietZone;
    if (qr.moduleRows[row]?.[column] === "1") {
      raster[y * qr.rowBytes + (x >> 3)] |= 0x80 >> (x & 7);
    }
  }
}
assert.deepEqual(raster, Buffer.from(qr.rasterBase64, "base64"));
assert.equal(createHash("sha256").update(raster).digest("hex"), qr.rasterSha256);
assert.equal(qr.rasterSha256, "63277bcfafd0e792b6d5d54befa95b9d4d8704ebbe184213b4c4fbca67e28229");

const javaString = (value) => JSON.stringify(value);
const source = `// Generated by native/generate-receipt-games-qr.mjs. Do not edit by hand.
// Source: tools/receipt-bridge/receipt-games-qr.mjs, the browser/TCP receipt grid.
package uk.co.mealdeck.printer;

/** Fixed public games QR. No order data, remote resource or mutable grid input. */
public final class ReceiptGamesQr {
    public static final String DESTINATION = ${javaString(qr.targetUrl)};
    public static final String DISPLAY_URL = ${javaString(qr.displayUrl)};
    public static final String HEADING = ${javaString(qr.heading)};
    public static final String SUBTITLE = ${javaString(qr.subtitle)};
    public static final int MODULE_COUNT = ${qr.moduleCount};
    public static final int QUIET_ZONE = ${qr.quietZone};
    public static final int MODULE_PIXELS = ${qr.scale};
    /** Includes the complete four-module white border on all sides. */
    public static final int SIZE_PX = ${qr.width};
    public static final String RASTER_SHA256 = ${javaString(qr.rasterSha256)};

    // A single immutable String keeps the reviewed data grid private.
    private static final String MODULES =
${qr.moduleRows.map((row, index) => `        ${javaString(row)}${index === qr.moduleRows.length - 1 ? ";" : " +"}`).join("\n")}

    private ReceiptGamesQr() {}

    /** Reads one data module, excluding the quiet zone. Coordinates are row/column. */
    public static boolean darkAt(int row, int column) {
        if (row < 0 || row >= MODULE_COUNT || column < 0 || column >= MODULE_COUNT) {
            throw new IllegalArgumentException("invalid_fixed_receipt_qr_coordinate");
        }
        return MODULES.charAt(row * MODULE_COUNT + column) == '1';
    }
}
`;

const args = process.argv.slice(2);
assert.ok(args.length === 0 || (args.length === 1 && args[0] === "--check"), "Expected only optional --check");
const output = fileURLToPath(new URL("src/main/java/uk/co/mealdeck/printer/ReceiptGamesQr.java", import.meta.url));
if (args[0] === "--check") {
  assert.equal(await readFile(output, "utf8"), source, "Regenerate the fixed native receipt games QR");
  console.log("Native receipt games QR matches the trusted grid and raster.");
} else {
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, source);
  console.log("Generated native receipt games QR from the trusted grid.");
}
