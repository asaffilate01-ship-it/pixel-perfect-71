/** Reproduce the owner's eight fixed receipt promotions for all renderers.
 * Build-time qrcode/Pillow only. Runtime code accepts no URL or image input.
 * Usage: node tools/receipt-bridge/build-receipt-promotions.mjs [--check] */
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import QRCode from "qrcode";
import { format } from "prettier";
import { receiptPromotionSpec } from "./receipt-promotion-spec.mjs";

const QUIET_ZONE = 4;
const SCALE = 6;
const QR_OPTIONS = Object.freeze({ version: 4, errorCorrectionLevel: "Q" });
const NATIVE = new URL("../../apps/mealdeck-printer/", import.meta.url);

async function qrAsset(targetUrl) {
  const symbol = QRCode.create(targetUrl, QR_OPTIONS);
  const moduleCount = symbol.modules.size;
  assert.equal(moduleCount, 33);
  const moduleRows = Array.from({ length: moduleCount }, (_, y) =>
    Array.from({ length: moduleCount }, (_, x) => (symbol.modules.get(y, x) ? "1" : "0")).join(""),
  );
  const gridSize = moduleCount + QUIET_ZONE * 2;
  const width = gridSize * SCALE;
  const height = width;
  const rowBytes = Math.ceil(width / 8);
  const raster = Buffer.alloc(rowBytes * height);
  const paths = [];
  for (let y = 0; y < moduleCount; y++) {
    let x = 0;
    while (x < moduleCount) {
      if (moduleRows[y][x] !== "1") {
        x++;
        continue;
      }
      const start = x;
      while (x < moduleCount && moduleRows[y][x] === "1") x++;
      const length = x - start;
      paths.push(`M${start + QUIET_ZONE} ${y + QUIET_ZONE}h${length}v1h-${length}z`);
    }
  }
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const row = Math.floor(y / SCALE) - QUIET_ZONE;
      const column = Math.floor(x / SCALE) - QUIET_ZONE;
      if (moduleRows[row]?.[column] === "1") raster[y * rowBytes + (x >> 3)] |= 0x80 >> (x & 7);
    }
  }
  const png = await QRCode.toBuffer(targetUrl, {
    ...QR_OPTIONS,
    margin: QUIET_ZONE,
    scale: SCALE,
    type: "png",
    color: { dark: "#000000ff", light: "#ffffffff" },
    rendererOpts: { deflateLevel: 9, deflateStrategy: 3 },
  });
  return {
    png,
    metadata: {
      width,
      height,
      rowBytes,
      viewBoxWidth: gridSize,
      viewBoxHeight: gridSize,
      version: QR_OPTIONS.version,
      errorCorrectionLevel: QR_OPTIONS.errorCorrectionLevel,
      mask: symbol.maskPattern,
      moduleCount,
      quietZone: QUIET_ZONE,
      scale: SCALE,
      moduleRows,
      svgPath: paths.join(""),
      rasterSha256: createHash("sha256").update(raster).digest("hex"),
      rasterBase64: raster.toString("base64"),
    },
  };
}

const javaString = (value) => (value === null ? "null" : JSON.stringify(value));

function javaCatalogue(slots) {
  return `// Generated by tools/receipt-bridge/build-receipt-promotions.mjs. Do not edit by hand.
// The canonical sequence selects one fixed image; no receipt content becomes artwork.
package uk.co.mealdeck.printer;

import java.util.Locale;

/** The owner's eight-slot receipt rotation, shared with browser and TCP output. */
public final class ReceiptPromotion {
    public static final int COUNT = 8;
    private ReceiptPromotion() {}

    public static final class Slot {
        public final String id, kind, heading, subtitle, displayUrl, targetUrl;
        public final String resourceName, rasterSha256;
        public final int width, height;
        private Slot(String id, String kind, String heading, String subtitle, String displayUrl,
                     String targetUrl, String resourceName, int width, int height, String rasterSha256) {
            this.id = id; this.kind = kind; this.heading = heading; this.subtitle = subtitle;
            this.displayUrl = displayUrl; this.targetUrl = targetUrl; this.resourceName = resourceName;
            this.width = width; this.height = height; this.rasterSha256 = rasterSha256;
        }
    }

    private static final Slot[] SLOTS = {
${slots.map((slot) => `        new Slot(${[slot.id, slot.kind, slot.heading, slot.subtitle, slot.displayUrl, slot.targetUrl, slot.resourceName].map(javaString).join(", ")}, ${slot.width}, ${slot.height}, ${javaString(slot.rasterSha256)})`).join(",\n")}
    };

    /** Pure selection: never reads copy number, time, job ID, settings or a counter. */
    public static Slot forOrder(String orderNumber, String orderId) {
        return SLOTS[indexForOrder(orderNumber, orderId)];
    }

    public static int indexForOrder(String orderNumber, String orderId) {
        if (orderNumber != null && orderNumber.matches("(?!0000$)(?:[0-9]{4}|[1-9][0-9]{4,18})")) {
            int remainder = 0;
            for (int i = 0; i < orderNumber.length(); i++)
                remainder = (remainder * 10 + orderNumber.charAt(i) - '0') % COUNT;
            return (remainder + COUNT - 1) % COUNT;
        }
        if (orderId == null || !orderId.matches("(?i)[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}"))
            throw new IllegalArgumentException("A canonical order identity is required for the receipt promotion.");
        String identity = orderId.toLowerCase(Locale.ROOT);
        int hash = 0x811c9dc5;
        for (int i = 0; i < identity.length(); i++) {
            hash ^= identity.charAt(i);
            hash *= 0x01000193;
        }
        return Integer.remainderUnsigned(hash, COUNT);
    }
}
`;
}

/** Fixed source catalogue only; callers cannot inject a QR destination/logo. */
export async function buildReceiptPromotions() {
  assert.equal(receiptPromotionSpec.length, 8);
  assert.deepEqual(
    receiptPromotionSpec.map((slot) => slot.id),
    ["play", "tiktok", "instagram", "skorch", "tavo-chicken", "loadd", "moktl", "souvano"],
  );
  const builtLogos = spawnSync(
    process.env.MEALDECK_PYTHON_BIN || "python3",
    [fileURLToPath(new URL("build-promotion-logos.py", import.meta.url))],
    { encoding: "utf8", maxBuffer: 8 * 1024 * 1024, timeout: 30_000 },
  );
  if (builtLogos.error) throw builtLogos.error;
  if (builtLogos.status !== 0)
    throw new Error(`Approved promotion logo generation failed: ${builtLogos.stderr}`);
  const logos = JSON.parse(builtLogos.stdout);
  assert.deepEqual(
    Object.keys(logos),
    receiptPromotionSpec.filter((slot) => slot.kind === "brand").map((slot) => slot.logoId),
  );
  const slots = [];
  const outputs = [];
  for (const spec of receiptPromotionSpec) {
    let png, metadata;
    if (spec.kind === "qr") {
      ({ png, metadata } = await qrAsset(spec.targetUrl));
    } else {
      const { pngBase64, ...logo } = logos[spec.logoId];
      png = Buffer.from(pngBase64, "base64");
      metadata = logo;
    }
    const { logoId: _logoId, ...presentation } = spec;
    const resourceName = `receipt_promo_${spec.id.replaceAll("-", "_")}`;
    const slot = { ...presentation, ...metadata, resourceName };
    assert.ok(slot.width > 0 && slot.width <= 288 && slot.height > 0 && slot.height <= 246);
    slots.push(slot);
    outputs.push([new URL(`assets/receipt-promo-${spec.id}.png`, import.meta.url), png]);
    outputs.push([
      new URL(`android/app/src/main/res/drawable-nodpi/${resourceName}.png`, NATIVE),
      png,
    ]);
  }
  const serialised = slots
    .map((slot) => {
      const encoded = JSON.stringify(slot, null, 2).replace(
        /"moduleRows": (\[[\s\S]*?\])/,
        '"moduleRows": Object.freeze($1)',
      );
      return `Object.freeze(${encoded})`;
    })
    .join(",\n");
  const module = await format(
    "// Generated by build-receipt-promotions.mjs. Do not edit by hand.\n" +
      "// Fixed public artwork and destinations; never supplied by an order.\n" +
      `export const receiptPromotionAssets = Object.freeze([${serialised}]);\n`,
    { parser: "babel", printWidth: 100 },
  );
  outputs.push([new URL("receipt-promotion-assets.mjs", import.meta.url), module]);
  outputs.push([
    new URL("native/src/main/java/uk/co/mealdeck/printer/ReceiptPromotion.java", NATIVE),
    javaCatalogue(slots),
  ]);
  return { slots, outputs };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  assert.ok(args.length === 0 || (args.length === 1 && args[0] === "--check"));
  const { slots, outputs } = await buildReceiptPromotions();
  for (const [url, value] of outputs) {
    if (args[0] === "--check") {
      assert.deepEqual(await readFile(url), Buffer.from(value), `Regenerate ${fileURLToPath(url)}`);
    } else {
      await mkdir(dirname(fileURLToPath(url)), { recursive: true });
      await writeFile(url, value);
    }
  }
  console.log(
    `${args[0] === "--check" ? "Verified" : "Generated"} ${slots.length} fixed promotions, shared browser/TCP rasters and native images.`,
  );
}
