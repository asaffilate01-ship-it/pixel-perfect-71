/** Reproduce the fixed games QR. Run with --check to verify committed output.
 * qrcode is a build-time tool only: receipt rendering uses the generated data.
 * There is deliberately no caller-supplied destination, payload or artwork. */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import QRCode from "qrcode";
import { format } from "prettier";

const TARGET = "https://mealdeck.co.uk/play/receipt";
const QUIET_ZONE = 4;
const SCALE = 6;
const QR_OPTIONS = { version: 4, errorCorrectionLevel: "Q" };

/** No arguments: the public receipt destination is fixed in reviewed source. */
export async function buildReceiptGamesQr() {
  const symbol = QRCode.create(TARGET, QR_OPTIONS);
  if (symbol.modules.size !== 33) throw new Error("Unexpected fixed QR version");
  const moduleRows = Array.from({ length: symbol.modules.size }, (_, y) =>
    Array.from({ length: symbol.modules.size }, (_, x) =>
      symbol.modules.get(y, x) ? "1" : "0",
    ).join(""),
  );
  const gridSize = symbol.modules.size + QUIET_ZONE * 2;
  const width = gridSize * SCALE;
  const height = width;
  const rowBytes = Math.ceil(width / 8);
  const raster = Buffer.alloc(rowBytes * height);
  const paths = [];
  for (let y = 0; y < symbol.modules.size; y++) {
    let x = 0;
    while (x < symbol.modules.size) {
      if (moduleRows[y][x] !== "1") {
        x++;
        continue;
      }
      const start = x;
      while (x < symbol.modules.size && moduleRows[y][x] === "1") x++;
      const run = x - start;
      paths.push(`M${start + QUIET_ZONE} ${y + QUIET_ZONE}h${run}v1h-${run}z`);
    }
  }
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const sourceY = Math.floor(y / SCALE) - QUIET_ZONE;
      const sourceX = Math.floor(x / SCALE) - QUIET_ZONE;
      if (moduleRows[sourceY]?.[sourceX] === "1")
        raster[y * rowBytes + (x >> 3)] |= 0x80 >> (x & 7);
    }
  }
  const data = {
    targetUrl: TARGET,
    displayUrl: "mealdeck.co.uk/play",
    heading: "Got a minute? Play MealDeck",
    subtitle: "Scan for free food games",
    version: 4,
    errorCorrectionLevel: "Q",
    mask: symbol.maskPattern,
    moduleCount: symbol.modules.size,
    quietZone: QUIET_ZONE,
    gridSize,
    scale: SCALE,
    width,
    height,
    rowBytes,
    rasterSha256: createHash("sha256").update(raster).digest("hex"),
    svgPath: paths.join(""),
    moduleRows,
    rasterBase64: raster.toString("base64"),
  };
  const serialised = JSON.stringify(data, null, 2).replace(
    /"moduleRows": (\[[\s\S]*?\])/,
    '"moduleRows": Object.freeze($1)',
  );
  const module = await format(
    "// Generated by build-games-qr.mjs. Do not edit by hand.\n" +
      "// Fixed public destination and pixels; never supplied by an order.\n" +
      `export const receiptGamesQr = Object.freeze(${serialised});\n`,
    { parser: "babel", printWidth: 100 },
  );
  const png = await QRCode.toBuffer(TARGET, {
    ...QR_OPTIONS,
    margin: QUIET_ZONE,
    scale: SCALE,
    type: "png",
    color: { dark: "#000000ff", light: "#ffffffff" },
    rendererOpts: { deflateLevel: 9, deflateStrategy: 3 },
  });
  return { module, png, data };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.slice(2).some((argument) => argument !== "--check"))
    throw new Error("Usage: node tools/receipt-bridge/build-games-qr.mjs [--check]");
  const generated = await buildReceiptGamesQr();
  const files = [
    [new URL("./receipt-games-qr.mjs", import.meta.url), generated.module],
    [new URL("./assets/mealdeck-games-qr.png", import.meta.url), generated.png],
  ];
  for (const [url, value] of files) {
    if (process.argv.includes("--check")) {
      const existing = await readFile(url);
      if (!existing.equals(Buffer.from(value)))
        throw new Error(`Generated QR differs: ${fileURLToPath(url)}`);
    } else await writeFile(url, value);
  }
  console.log(
    `Fixed receipt QR: ${generated.data.width}×${generated.data.height}, ` +
      `${generated.data.moduleCount} modules, Q correction, ${QUIET_ZONE}-module quiet zone.`,
  );
  console.log(`Raster SHA256: ${generated.data.rasterSha256}`);
}
