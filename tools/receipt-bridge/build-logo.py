"""Reproduce the fixed thermal logo from the complete approved MealDeck artwork.

No crop, redrawing, caller URL or runtime image decoding. Thermal output is the
approved artwork composited on white, proportionally resized and thresholded.
"""

from base64 import b64encode
from hashlib import sha256
from pathlib import Path
import json

from PIL import Image

root = Path(__file__).resolve().parents[2]
source = root / "src/assets/approved-logos/mealdeck.webp"
manifest = json.loads((source.parent / "manifest.json").read_text())
approved = next(row for row in manifest["logos"] if row["id"] == "mealdeck")
image = Image.open(source).convert("RGBA")
assert sha256(image.tobytes()).hexdigest() == approved["rgba_sha256"]
assert image.size == (approved["width"], approved["height"])

width = 256
height = round(image.height * width / image.width)
white = Image.new("RGBA", image.size, "white")
white.alpha_composite(image)
grey = white.convert("L").resize((width, height), Image.Resampling.LANCZOS)
mono = grey.point(lambda value: 0 if value < 180 else 255, mode="1")
row_bytes = (width + 7) // 8
# ESC/POS raster bit 1 is black; Pillow's mode 1 uses 1 for white.
raster = bytes(value ^ 255 for value in mono.tobytes())
assert len(raster) == row_bytes * height

destination = Path(__file__).resolve().parent
assets = destination / "assets"
assets.mkdir(exist_ok=True)
mono.save(assets / "mealdeck-thermal-logo.png")
encoded = b64encode(raster).decode("ascii")
chunks = [encoded[index : index + 100] for index in range(0, len(encoded), 100)]
module = (
    "// Generated by build-logo.py from the complete approved artwork.\n"
    "// Fixed trusted pixels only; receipt data cannot supply or alter this logo.\n"
    "export const receiptLogo = Object.freeze({\n"
    f"  width: {width},\n  height: {height},\n  rowBytes: {row_bytes},\n"
    f"  sourceRgbaSha256: {json.dumps(approved['rgba_sha256'])},\n"
    f"  rasterSha256: {json.dumps(sha256(raster).hexdigest())},\n"
    "  rasterBase64:\n    "
    + " +\n    ".join(json.dumps(chunk) for chunk in chunks)
    + ",\n});\n"
)
(destination / "receipt-logo.mjs").write_text(module)
print(f"Approved logo: {width}x{height}; {len(raster)} fixed raster bytes")
print(f"Raster SHA256: {sha256(raster).hexdigest()}")
